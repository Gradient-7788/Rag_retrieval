import re
from abc import ABC, abstractmethod
from typing import List

class BaseQueryRewriter(ABC):
    @abstractmethod
    def rewrite(self, query: str) -> List[str]:
        """Returns list of queries (including original or expanded/transformed queries)."""
        pass

class DirectQueryRewriter(BaseQueryRewriter):
    """Passes query through unmodified."""
    def rewrite(self, query: str) -> List[str]:
        return [query]

class HyDEQueryRewriter(BaseQueryRewriter):
    """
    Hypothetical Document Embeddings (HyDE).
    Generates hypothetical passage answering the query to retrieve semantically similar passages.
    """
    def __init__(self, llm_generator=None):
        self.llm_generator = llm_generator

    def rewrite(self, query: str) -> List[str]:
        # NOTE: with the offline mock LLM the "hypothetical document" is a template containing the
        # query, so offline HyDE behaves like light query expansion. Use llm_backend="openai" for
        # real HyDE (and expect +hundreds of ms per query for the generation call).
        if self.llm_generator:
            prompt = f"Write a brief technical passage that directly answers the question: '{query}'"
            hypothetical_doc = self.llm_generator.generate(prompt)
            return [hypothetical_doc]
        # Algorithmic synthetic fallback for fast offline benchmarking
        hypothetical_doc = f"Detailed explanation regarding {query}. Key technical details, definitions, background, context, and exact mechanics of {query} within the system."
        return [query, hypothetical_doc]

class MultiQueryRewriter(BaseQueryRewriter):
    """Multi-query expansion by aspect decomposition.

    Multi-aspect questions ("How does X work, and what does Y cost?") are split into one
    sub-query per aspect, so each aspect gets its own retrieval instead of being averaged into a
    single query vector. With an LLM available, sub-queries are generated by the LLM; offline, a
    rule-based splitter on clause boundaries is used. The original query is always kept.
    """
    SPLIT = re.compile(r",\s*and\s+|\s+and\s+(?=(?:how|what|which|why|when|where|is|are|does|do|can)\b)|;\s*|\?\s+", re.I)

    def __init__(self, llm_generator=None, use_llm: bool = False):
        self.llm_generator = llm_generator
        self.use_llm = use_llm

    def rewrite(self, query: str) -> List[str]:
        if self.use_llm and self.llm_generator is not None:
            text = self.llm_generator.generate(
                f"Split this question into its separate information needs, one short search query per line:\n{query}")
            subs = [l.strip("-* ").strip() for l in text.splitlines() if l.strip()]
        else:
            subs = [p.strip(" ?") for p in self.SPLIT.split(query) if len(p.strip(" ?").split()) >= 3]
        out = [query]
        for sq in subs:
            if sq and sq.lower() != query.strip(" ?").lower() and sq not in out:
                out.append(sq)
        return out

class StepBackQueryRewriter(BaseQueryRewriter):
    """
    Step-Back Prompting: Abstracts specific question to high-level concept query.
    """
    def rewrite(self, query: str) -> List[str]:
        words = query.strip().split()
        if len(words) > 3:
            # Abstract high level step back query
            abstract_q = " ".join(words[:4]) + " fundamental principles and concepts"
            return [query, abstract_q]
        return [query, f"{query} general concept and overview"]

class KeywordExpansionRewriter(BaseQueryRewriter):
    """Adds a keyword-only variant of the query (stopwords and question words removed), which
    sharpens BM25 and reduces the weight of filler words in dense retrieval."""
    STOP = set("a an the of to in on for and or is are was were be how what which why when where does do "
               "did can could should would it its this that with by from as at into than then".split())

    def rewrite(self, query: str) -> List[str]:
        kws = [w for w in re.findall(r"[\w-]+", query.lower()) if w not in self.STOP and len(w) > 2]
        return [query, " ".join(kws)] if kws else [query]
